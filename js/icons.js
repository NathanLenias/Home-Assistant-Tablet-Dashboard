export function icon(name) {
  const filled = Object.prototype.hasOwnProperty.call(FILL, name);
  const paths = filled ? FILL[name] : STROKE[name];
  if (!paths) return '';
  const attrs = filled
    ? 'fill="currentColor"'
    : 'fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"';
  const body = paths.map((d) => `<path d="${d}"/>`).join('');
  return `<svg class="icon" viewBox="0 0 24 24" ${attrs} aria-hidden="true">${body}</svg>`;
}

// Remplit tous les éléments porteurs d'un attribut data-icon.
export function paintIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (el.dataset.painted === el.dataset.icon) return;
    el.insertAdjacentHTML('afterbegin', icon(el.dataset.icon));
    el.dataset.painted = el.dataset.icon;
  });
}
